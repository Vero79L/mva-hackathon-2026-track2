"""Case-driven candidate triage for N-of-1 rare-disease drug repurposing.

Disease-agnostic. Validates every input against an explicit contract; unknown or
malformed inputs BLOCK — they never pass silently. The engine produces a
COMPUTED assessment only; the human research judgment lives in the canonical
candidate table and is never inferred from, or allowed to overwrite, the inputs.

Contract (a candidate dict):
  id, drug                       : required, non-empty
  net_effect                     : one of NET_EFFECTS
  evidence_distance              : int 0-5
  rescue_in_relevant_cells       : real bool
  properties                     : list, each in the allowed property enum (from scoring)
  competition_eligibility        : ELIGIBLE | INELIGIBLE | UNKNOWN  (absent => UNKNOWN)
  safety_assessment              : dict {oncology,renal,growth: one of SAFETY_STATUS}
  objective_class                : restore | mitigate | deselect | protect — which therapeutic
                                   objective the candidate claims to serve. Only consulted when
                                   the case carries a scenario block (see below); a candidate with
                                   no declared class BLOCKS under a scenario rather than passing.

Scenario sensitivity: a scenario case file (generated by 14_build_scenarios.py) carries
scenario.implications.objective_validity = {class: valid|invalid|conditional}. When present, a
candidate whose claimed objective class is "invalid" in that scenario is REJECTed; "conditional"
is flagged AND blocks STRONG (an unresolved condition is not strength). A scenario block that is
present but malformed BLOCKs at gate "scenario-validation" rather than being treated as absent. Without a scenario block the gate is inert, so the base case and the
synthetic case behave exactly as before.
STRONG requires: eligibility ELIGIBLE AND ev-dist>=3 AND rescue True AND every
safety gate explicitly assessed AND no unresolved risk (only "not_observed" supports
STRONG; "confirmed_risk" and "contradictory" are assessed-but-unacceptable). Missing
assessment or unknown eligibility can never reach STRONG. Unknown fields and unknown
property values BLOCK. A properties[] risk flag that contradicts its safety gate
("nephrotoxic" with renal "not_observed") is a bad INPUT and BLOCKs (gate
"risk-input-conflict"), it is never silently resolved.

Usage:
    uv run src/triage.py --case config/cases/bub1b_mva.yaml \
        --candidates evidence/candidates_from_canonical.yaml --scoring config/scoring.yaml
    uv run src/triage.py --selftest
"""
from __future__ import annotations
# Make stdout/stderr UTF-8 regardless of the machine's locale: this repo is read and run by
# reviewers on systems where the preferred encoding may be ASCII, and a crash while *printing*
# a result is still a failed reproduction.
import sys as _sys
for _s in (_sys.stdout, _sys.stderr):
    try: _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception: pass

import argparse, sys
from pathlib import Path
import yaml

NET_EFFECTS = {"strengthen", "inhibit", "restore_or_bypass", "weaken", "none"}
ELIGIBILITY = {"ELIGIBLE", "INELIGIBLE", "UNKNOWN"}
SAFETY_GATES = ("oncology", "renal", "growth")
SAFETY_STATUS = {"confirmed_risk", "not_observed", "not_assessed", "contradictory"}
KNOWN_CANDIDATE_FIELDS = {
    "id", "drug", "net_effect", "evidence_distance", "rescue_in_relevant_cells",
    "properties", "competition_eligibility", "safety_assessment", "objective_class",
    "safety_gap_declared"}
OBJECTIVE_CLASSES = {"restore", "mitigate", "deselect", "protect"}
OBJECTIVE_VALIDITY = {"valid", "invalid", "conditional"}
# property -> the safety gate it belongs to (Spec 0 §2.1)
PROPERTY_SAFETY_GATE = {
    "pro_tumor": "oncology", "pro_proliferative": "oncology",
    "increases_CIN": "oncology", "immunosuppressive": "oncology",
    "nephrotoxic": "renal", "renal_cleared_narrow_TI": "renal",
    "anti_anabolic": "growth", "growth_suppressive": "growth",
}


def load(p):
    return yaml.safe_load(Path(p).read_text(encoding="utf-8"))


# ---- allowed property enum derived from the scoring config (no drift) ----

def allowed_properties(scoring):
    props = {"approved_or_credible_pediatric_path"}
    for g in scoring["hard_gates"].values():
        for rule in g["rule"].values():
            for lst in rule.values():
                props.update(lst or [])
    return props


def known_levels(scoring, gate_key):
    return set(scoring["hard_gates"][gate_key]["rule"].keys())


# ---- validation ----

def validate_case(case, scoring):
    errs = []
    if not isinstance(case, dict):
        return [f"case is not a mapping ({type(case).__name__})"]
    if case.get("defect_direction") not in scoring["directionality"]:
        errs.append(f"unknown defect_direction '{case.get('defect_direction')}'")
    pc = case.get("patient_constraints")
    if not isinstance(pc, dict):
        errs.append(f"patient_constraints must be a mapping (got {type(pc).__name__})")
        return errs
    for gk in ("G1_oncology", "G2_pediatric", "G3_renal", "G4_growth"):
        driver = scoring["hard_gates"][gk]["driver"]
        if pc.get(driver) not in known_levels(scoring, gk):
            errs.append(f"{gk}: constraint '{driver}'='{pc.get(driver)}' is unknown")
    return errs


def validate_candidate(cand, scoring):
    if cand is None or not isinstance(cand, dict):
        return [f"candidate is not a mapping ({type(cand).__name__})"]
    errs = []
    unknown = set(cand) - KNOWN_CANDIDATE_FIELDS
    if unknown:
        errs.append(f"unknown field(s) {sorted(unknown)} — reject rather than ignore")
    if not cand.get("id") or not cand.get("drug"):
        errs.append("missing id or drug")
    if cand.get("net_effect") not in NET_EFFECTS:
        errs.append(f"net_effect '{cand.get('net_effect')}' invalid")
    ed = cand.get("evidence_distance")
    if isinstance(ed, bool) or not isinstance(ed, int) or not (0 <= ed <= 5):
        errs.append(f"evidence_distance '{ed}' must be int 0-5")
    if not isinstance(cand.get("rescue_in_relevant_cells", False), bool):
        errs.append("rescue_in_relevant_cells must be a real boolean")
    props = cand.get("properties", [])
    if not isinstance(props, list):
        errs.append("properties must be a list")
    else:
        bad = set(props) - allowed_properties(scoring)
        if bad:
            errs.append(f"unknown property value(s) {sorted(bad)}")
    elig = cand.get("competition_eligibility", "UNKNOWN")
    if elig not in ELIGIBILITY:
        errs.append(f"competition_eligibility '{elig}' invalid")
    oc = cand.get("objective_class")
    if oc is not None and oc not in OBJECTIVE_CLASSES:
        errs.append(f"objective_class '{oc}' invalid")
    sa = cand.get("safety_assessment")
    if sa is not None:
        if not isinstance(sa, dict):
            errs.append("safety_assessment must be a mapping")
        else:
            bad = {v for v in sa.values() if v not in SAFETY_STATUS}
            if bad:
                errs.append(f"safety_assessment status(es) {sorted(bad)} invalid")
    return errs


# ---- gate logic ----

def directionality_ok(cand, case, scoring):
    need = scoring["directionality"][case["defect_direction"]]
    got = cand.get("net_effect")
    return (got == need), f"net_effect '{got}' vs required '{need}'"


def gate(cand, case, scoring, gate_key):
    g = scoring["hard_gates"][gate_key]
    level = case["patient_constraints"].get(g["driver"])
    rule = g["rule"].get(level, {})
    props = set(cand.get("properties", []))
    for action, props_list in rule.items():
        want = set(props_list or [])
        hit = props & want
        if action.startswith("reject_if") and hit:
            return "REJECT", f"{gate_key}[{level}]: {sorted(hit)}"
        if action.startswith("require") and want and not hit:
            return "REJECT", f"{gate_key}[{level}]: missing one of {sorted(want)}"
        if action.startswith("flag_if") and hit:
            return "FLAG", f"{gate_key}[{level}]: watch {sorted(hit)}"
    return "PASS", f"{gate_key}[{level}]: ok"


def scenario_objective_validity(case):
    """Return (objective_validity_map, errors).

    A case with no `scenario` key at all legitimately has no scenario gate: returns
    (None, []). A case that DOES carry a scenario but whose block is malformed returns
    (None, [errors]) and must BLOCK — a broken scenario is a bad input, not an absent one.
    Silently treating it as "no scenario" is exactly the laundering this engine exists to refuse.
    """
    if "scenario" not in case:
        return None, []
    sc = case["scenario"]
    if not isinstance(sc, dict):
        return None, [f"scenario must be a mapping, got {type(sc).__name__}"]
    imp = sc.get("implications")
    if not isinstance(imp, dict):
        return None, ["scenario.implications is missing or not a mapping"]
    ov = imp.get("objective_validity")
    if not isinstance(ov, dict):
        return None, ["scenario.implications.objective_validity is missing or not a mapping"]
    errs = [f"objective_validity['{k}'] = {v!r} is not one of {sorted(OBJECTIVE_VALIDITY)}"
            for k, v in sorted(ov.items()) if v not in OBJECTIVE_VALIDITY]
    missing = OBJECTIVE_CLASSES - set(ov)
    if missing:
        errs.append(f"objective_validity does not cover class(es) {sorted(missing)}")
    return (None if errs else ov), errs


def safety_state(cand):
    """Return (all_assessed, unresolved_risk, notes).

    not_assessed   -> not assessed, cannot be STRONG
    confirmed_risk -> confirmed risk, cannot be STRONG (assessed != acceptable)
    contradictory  -> evidence conflicts, cannot be STRONG
    not_observed   -> the only state that supports STRONG
    """
    sa = cand.get("safety_assessment") or {}
    notes, unassessed, unresolved = [], False, False
    for g in SAFETY_GATES:
        st = sa.get(g, "not_assessed")
        if st == "not_assessed":
            unassessed = True; notes.append(f"safety[{g}] not assessed")
        elif st in ("confirmed_risk", "contradictory"):
            unresolved = True; notes.append(f"safety[{g}] {st} -> unresolved risk")
    return (not unassessed), unresolved, notes


def safety_input_conflicts(cand):
    """Explain every place where properties[] and safety_assessment contradict each other."""
    sa = cand.get("safety_assessment") or {}
    out = []
    for p in cand.get("properties", []):
        gate_name = PROPERTY_SAFETY_GATE.get(p)
        if gate_name and sa.get(gate_name) == "not_observed":
            out.append(f"conflict: property '{p}' vs safety[{gate_name}]='not_observed'")
    return out


def undeclared_safety_gaps(cand):
    """Gates whose assessed status is unresolved but which carry no properties[] tag.

    The hard gates read properties[] only. So a candidate can be assessed as
    `confirmed_risk` or `contradictory` on a gate, carry no property for it, and still
    PASS that gate -- the gate is silent about a risk the candidate's own safety block
    admits. That asymmetry is real and we do not patch it by inventing a tag (changing a
    property after seeing which candidate a rule would catch is rule-fitting). Instead the
    gap is made explicit: the engine returns it, prints it, and `build_views.py` refuses to
    build unless the canonical entry declares exactly this set in `safety_gap_declared`.
    """
    sa = cand.get("safety_assessment") or {}
    tagged = {PROPERTY_SAFETY_GATE[p] for p in cand.get("properties", [])
              if p in PROPERTY_SAFETY_GATE}
    return sorted(g for g in SAFETY_GATES
                  if sa.get(g, "not_assessed") in ("confirmed_risk", "contradictory", "not_assessed")
                  and g not in tagged)


def unactioned_risk_tags(cand, case, scoring):
    """Risk tags the gate can SEE but has no rule for at this patient's level.

    G1 rejects `immunosuppressive` only when malignancy_status is `active`; at `history`
    and `predisposition` it is not in the reject list, so a tagged immunosuppressant passes
    the oncology gate. G4 only ever flags. We report this rather than rewriting the rule:
    changing a scoring rule after seeing which candidate it would catch is rule-fitting and
    would invalidate every other verdict the rule produced. Reporting it costs nothing and
    is checkable by a reader who has the config open.
    """
    out = []
    for gk, g in scoring["hard_gates"].items():
        level = case["patient_constraints"].get(g["driver"])
        rule = g["rule"].get(level, {}) or {}
        actionable = set()
        for action, lst in rule.items():
            if action.startswith(("reject_if", "require")):
                actionable |= set(lst or [])
        for p in cand.get("properties", []):
            gate_axis = PROPERTY_SAFETY_GATE.get(p)
            if gate_axis and gk.endswith(gate_axis) and p not in actionable:
                out.append(f"{gk}[{level}]: '{p}' is a recognised risk tag but this level's "
                           f"rule does not act on it")
    return sorted(set(out))


def triage_one(cand, case, scoring):
    cerr = validate_candidate(cand, scoring)
    if cerr:
        cid = cand.get("id", "?") if isinstance(cand, dict) else "?"
        drug = cand.get("drug", "?") if isinstance(cand, dict) else "?"
        return {"id": cid, "drug": drug, "verdict": "BLOCKED",
                "gate": "input-validation", "reasons": cerr}
    conflicts = safety_input_conflicts(cand)
    if conflicts:
        return {"id": cand["id"], "drug": cand["drug"], "verdict": "BLOCKED",
                "gate": "risk-input-conflict", "reasons": conflicts}
    reasons, flags = [], []
    elig = cand.get("competition_eligibility", "UNKNOWN")
    if elig == "INELIGIBLE":
        return {"id": cand["id"], "drug": cand["drug"], "verdict": "REJECT",
                "gate": "eligibility", "reasons": ["competition_eligibility INELIGIBLE"]}
    ok, why = directionality_ok(cand, case, scoring)
    reasons.append(why)
    if not ok:
        return {"id": cand["id"], "drug": cand["drug"], "verdict": "REJECT",
                "gate": "directionality", "reasons": reasons}
    ov, ov_errs = scenario_objective_validity(case)
    if ov_errs:
        return {"id": cand["id"], "drug": cand["drug"], "verdict": "BLOCKED",
                "gate": "scenario-validation", "reasons": ov_errs}
    objective_unresolved = False
    if ov is not None:
        sid = case["scenario"].get("id", "?")
        cls = cand.get("objective_class")
        if cls is None:
            return {"id": cand["id"], "drug": cand["drug"], "verdict": "BLOCKED",
                    "gate": "objective-class-missing",
                    "reasons": [f"scenario {sid} is active but the candidate declares no objective_class"]}
        verdict = ov.get(cls)
        if verdict not in OBJECTIVE_VALIDITY:
            return {"id": cand["id"], "drug": cand["drug"], "verdict": "BLOCKED",
                    "gate": "objective-validity",
                    "reasons": [f"scenario {sid}: objective_validity['{cls}'] = {verdict!r} is not a known value"]}
        reasons.append(f"scenario {sid}: objective '{cls}' is {verdict}")
        if verdict == "invalid":
            return {"id": cand["id"], "drug": cand["drug"], "verdict": "REJECT",
                    "gate": f"objective-validity[{sid}]", "reasons": reasons}
        if verdict == "conditional":
            # a conditionally valid objective is an UNRESOLVED condition: it may be flagged and
            # carried, but it must never reach the engine's strongest tier.
            objective_unresolved = True
            flags.append(f"objective-{cls}-conditional[{sid}]")
    for gk in ("G1_oncology", "G2_pediatric", "G3_renal", "G4_growth"):
        res, why = gate(cand, case, scoring, gk)
        reasons.append(why)
        if res == "REJECT":
            return {"id": cand["id"], "drug": cand["drug"], "verdict": "REJECT",
                    "gate": gk, "reasons": reasons}
        if res == "FLAG":
            flags.append(gk)
    ed = cand["evidence_distance"]
    assessed, unresolved, safety_notes = safety_state(cand)
    reasons.extend(safety_notes)
    strong = (elig == "ELIGIBLE" and ed >= 3
              and cand.get("rescue_in_relevant_cells") is True
              and assessed and not unresolved and not objective_unresolved)
    if objective_unresolved:
        reasons.append("objective validity is conditional in this scenario -> cannot be STRONG")
    tier = "STRONG" if strong else "CONDITIONAL"
    if tier == "CONDITIONAL" and elig != "ELIGIBLE":
        reasons.append(f"eligibility {elig} -> cannot be STRONG")
    unactioned = unactioned_risk_tags(cand, case, scoring)
    if unactioned:
        reasons.extend(unactioned)
    gaps = undeclared_safety_gaps(cand)
    if gaps:
        reasons.append("gate-silent safety axes (assessed unresolved, no properties[] tag, "
                       f"so the hard gate cannot see them): {gaps}")
    return {"id": cand["id"], "drug": cand["drug"], "verdict": tier,
            "gate": "passed", "flags": flags, "evidence_distance": ed,
            "eligibility": elig, "gate_silent_safety": gaps,
            "unactioned_risk_tags": unactioned, "reasons": reasons}


def run(case, scoring, cands):
    cerr = validate_case(case, scoring)
    if cerr:
        return {"case_blocked": cerr}, [{"id": "CASE", "drug": "-", "verdict": "BLOCKED",
                                         "gate": "case-validation", "reasons": cerr}]
    if not isinstance(cands, list):
        return {"case_blocked": ["candidates is not a list"]}, []
    return None, [triage_one(c, case, scoring) for c in cands]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--case")
    ap.add_argument("--candidates")
    ap.add_argument("--scoring", default="config/scoring.yaml")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest(a.scoring)
    case, scoring = load(a.case), load(a.scoring)
    blocked, out = run(case, scoring, load(a.candidates)["candidates"])
    if blocked:
        print("CASE BLOCKED — invalid manifest:")
        for e in blocked["case_blocked"]:
            print("  -", e)
        return 2
    order = {"STRONG": 0, "CONDITIONAL": 1, "REJECT": 2, "BLOCKED": 3}
    print(f"\n=== Triage: {case['case_id']} ({case['disease']}) ===")
    for r in sorted(out, key=lambda r: order.get(r["verdict"], 9)):
        flags = f" flags={r.get('flags')}" if r.get("flags") else ""
        gaps = f" gate-silent={r['gate_silent_safety']}" if r.get("gate_silent_safety") else ""
        unact = " unactioned-risk-tag" if r.get("unactioned_risk_tags") else ""
        print(f"[{r['verdict']:<11}] {r['drug'][:34]:<34} ({r['gate']}){flags}{gaps}{unact}")
    for r in out:
        for line in r.get("unactioned_risk_tags", []):
            print(f"  note {r['id']}: {line}")
    n = {k: sum(1 for r in out if r["verdict"] == k) for k in order}
    print("Summary:", n)
    return 3 if any(r["verdict"] == "BLOCKED" for r in out) else 0


def selftest(scoring_path):
    scoring = load(scoring_path)
    base_case = {"case_id": "t", "disease": "t", "defect_direction": "channel_overactivity",
                 "patient_constraints": {"age_group": "adult", "malignancy_status": "none",
                                         "renal": "normal", "growth": "normal"}}
    assessed = {"oncology": "not_observed", "renal": "not_observed", "growth": "not_observed"}

    def one(c):
        return triage_one(c, base_case, scoring)
    checks = []
    # 1. positive control WITH full safety assessment + eligible -> STRONG
    r = one({"id": "S1", "drug": "pos", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 3, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed})
    checks.append(("positive_strong", r["verdict"] == "STRONG", r["verdict"]))
    # 2. SAME but no safety assessment -> NOT STRONG
    r = one({"id": "S2", "drug": "p2", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 3, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE"})
    checks.append(("unassessed_not_strong", r["verdict"] != "STRONG", r["verdict"]))
    # 3. INELIGIBLE -> not STRONG (REJECT)
    r = one({"id": "S3", "drug": "p3", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 3, "rescue_in_relevant_cells": True,
             "competition_eligibility": "INELIGIBLE", "safety_assessment": assessed})
    checks.append(("ineligible_not_strong", r["verdict"] != "STRONG", r["verdict"]))
    # 4. unknown property -> BLOCKED
    r = one({"id": "S4", "drug": "p4", "net_effect": "inhibit", "properties": ["nephrotoxicc"],
             "evidence_distance": 3, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed})
    checks.append(("unknown_property_blocked", r["verdict"] == "BLOCKED", r["verdict"]))
    # 5. None candidate -> BLOCKED (no crash)
    r = one(None)
    checks.append(("null_candidate_blocked", r["verdict"] == "BLOCKED", r["verdict"]))
    # 6. wrong direction -> REJECT
    r = one({"id": "S6", "drug": "wd", "net_effect": "strengthen", "properties": [],
             "evidence_distance": 2, "rescue_in_relevant_cells": False,
             "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed})
    checks.append(("wrong_direction", r["gate"] == "directionality", r["gate"]))
    # 7. unknown defect_direction -> case BLOCKED
    checks.append(("unknown_direction",
                   len(validate_case(dict(base_case, defect_direction="x"), scoring)) > 0, "case"))
    # 8. ev-dist 999 + string "false" -> BLOCKED
    r = one({"id": "S8", "drug": "b", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 999, "rescue_in_relevant_cells": "false",
             "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed})
    checks.append(("bad_types_blocked", r["verdict"] == "BLOCKED", r["verdict"]))
    risky = {"oncology": "confirmed_risk", "renal": "confirmed_risk", "growth": "contradictory"}
    # 9. fully assessed but all confirmed risk -> NOT STRONG (2026-10-09 review failure case 1)
    r = one({"id": "S9", "drug": "risky", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 5, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE", "safety_assessment": risky})
    checks.append(("assessed_but_risky_not_strong", r["verdict"] != "STRONG", r["verdict"]))
    # 10. a single contradictory gate is enough to block STRONG
    r = one({"id": "S10", "drug": "contra", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 4, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE",
             "safety_assessment": {"oncology": "not_observed", "renal": "contradictory",
                                   "growth": "not_observed"}})
    checks.append(("contradictory_not_strong", r["verdict"] != "STRONG", r["verdict"]))
    # 11. properties vs safety_assessment conflict -> BLOCKED (review failure case 2)
    r = one({"id": "S11", "drug": "conflict", "net_effect": "inhibit",
             "properties": ["nephrotoxic"], "evidence_distance": 3,
             "rescue_in_relevant_cells": True, "competition_eligibility": "ELIGIBLE",
             "safety_assessment": {"oncology": "not_observed", "renal": "not_observed",
                                   "growth": "not_observed"}})
    checks.append(("risk_input_conflict_blocked",
                   r["verdict"] == "BLOCKED" and r["gate"] == "risk-input-conflict", r["gate"]))
    # 12. all not_observed + every other condition met -> still STRONG (guard against over-fixing)
    r = one({"id": "S12", "drug": "clean", "net_effect": "inhibit", "properties": [],
             "evidence_distance": 3, "rescue_in_relevant_cells": True,
             "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed})
    checks.append(("clean_still_strong", r["verdict"] == "STRONG", r["verdict"]))
    # 13-16. scenario-aware objective gate
    def scen(sid, validity):
        return dict(base_case, scenario={"id": sid, "implications": {"objective_validity": validity}})
    restore_invalid = {"restore": "invalid", "mitigate": "valid", "deselect": "valid", "protect": "valid"}
    restore_cond = {"restore": "conditional", "mitigate": "valid", "deselect": "valid", "protect": "valid"}
    cand_restore = {"id": "S13", "drug": "restore-class", "net_effect": "inhibit", "properties": [],
                    "evidence_distance": 3, "rescue_in_relevant_cells": True,
                    "competition_eligibility": "ELIGIBLE", "safety_assessment": assessed,
                    "objective_class": "restore"}
    # 13. objective invalid in this scenario -> REJECT
    r = triage_one(cand_restore, scen("S2", restore_invalid), scoring)
    checks.append(("objective_invalid_rejected",
                   r["verdict"] == "REJECT" and r["gate"] == "objective-validity[S2]", r["gate"]))
    # 14. objective conditional -> still passes, but flagged
    r = triage_one(cand_restore, scen("S3", restore_cond), scoring)
    checks.append(("objective_conditional_flagged",
                   r["verdict"] != "REJECT" and any("conditional" in f for f in r.get("flags", [])),
                   r.get("flags")))
    # 15. scenario active but no objective_class declared -> BLOCKED (unknown never passes silently)
    r = triage_one({k: v for k, v in cand_restore.items() if k != "objective_class"},
                   scen("S2", restore_invalid), scoring)
    checks.append(("objective_class_missing_blocked",
                   r["verdict"] == "BLOCKED" and r["gate"] == "objective-class-missing", r["gate"]))
    # 16. no scenario block -> the gate is inert (base/synthetic cases unchanged)
    r = one(cand_restore)
    checks.append(("no_scenario_gate_inert", r["verdict"] == "STRONG", r["verdict"]))
    # 17. a CONDITIONAL objective must never reach STRONG (red-team 2026-10-19: it did)
    r = triage_one(cand_restore, scen("S3", restore_cond), scoring)
    checks.append(("objective_conditional_not_strong", r["verdict"] != "STRONG", r["verdict"]))
    # 18-21. a scenario that is PRESENT but malformed must BLOCK, not fall back to "no scenario"
    for name, bad in (
        ("ov_not_a_mapping", {"id": "S9", "implications": {"objective_validity": "garbage"}}),
        ("implications_missing", {"id": "S9"}),
        ("key_typo", {"id": "S9", "implications": {"objective_validitee": {"restore": "invalid"}}}),
        ("scenario_not_a_mapping", "S9"),
    ):
        r = triage_one(cand_restore, dict(base_case, scenario=bad), scoring)
        checks.append((f"malformed_scenario_blocked__{name}",
                       r["verdict"] == "BLOCKED" and r["gate"] == "scenario-validation", r["gate"]))
    # 22. an unknown validity value must BLOCK rather than be read as permissive
    r = triage_one(cand_restore, scen("S9", {"restore": "mostly", "mitigate": "valid",
                                             "deselect": "valid", "protect": "valid"}), scoring)
    checks.append(("unknown_validity_blocked",
                   r["verdict"] == "BLOCKED" and r["gate"] == "scenario-validation", r["gate"]))
    # 23. objective_validity that does not cover all four classes must BLOCK
    r = triage_one(cand_restore, scen("S9", {"restore": "valid"}), scoring)
    checks.append(("incomplete_validity_blocked",
                   r["verdict"] == "BLOCKED" and r["gate"] == "scenario-validation", r["gate"]))

    # 24-27. the patient hard gates themselves: until now every self-test ran on an
    # adult/none/normal/normal base case, where G1 rejects only increases_CIN and G2/G3/G4
    # carry empty lists -- so gate()'s reject_if, require and flag_if branches had zero
    # coverage. These four run against this patient's actual constraint levels.
    patient_case = {"case_id": "t2", "disease": "t2", "defect_direction": "checkpoint_insufficiency",
                    "patient_constraints": {"age_group": "child", "malignancy_status": "history",
                                            "renal": "nephrocalcinosis", "growth": "restricted"}}

    def pat(c):
        return triage_one(c, patient_case, scoring)
    base_pat = {"net_effect": "strengthen", "evidence_distance": 3,
                "rescue_in_relevant_cells": True, "competition_eligibility": "ELIGIBLE"}
    # 24. a child with no pediatric path -> G2 REJECT (the `require` branch)
    r = pat(dict(base_pat, id="S24", drug="no-peds", properties=[], safety_assessment=assessed))
    checks.append(("gate_require_pediatric_rejects",
                   r["verdict"] == "REJECT" and r["gate"] == "G2_pediatric", r["gate"]))
    # 25. nephrotoxic + nephrocalcinosis -> G3 REJECT (the `reject_if` branch)
    r = pat(dict(base_pat, id="S25", drug="nephro",
                 properties=["approved_or_credible_pediatric_path", "nephrotoxic"],
                 safety_assessment={"oncology": "not_observed", "renal": "confirmed_risk",
                                    "growth": "not_observed"}))
    checks.append(("gate_reject_if_renal_rejects",
                   r["verdict"] == "REJECT" and r["gate"] == "G3_renal", r["gate"]))
    # 26. growth_suppressive + restricted growth -> FLAG, not reject (the `flag_if` branch)
    r = pat(dict(base_pat, id="S26", drug="growth",
                 properties=["approved_or_credible_pediatric_path", "growth_suppressive"],
                 safety_assessment={"oncology": "not_observed", "renal": "not_observed",
                                    "growth": "confirmed_risk"}))
    checks.append(("gate_flag_if_growth_flags",
                   r["verdict"] != "REJECT" and "G4_growth" in r.get("flags", []), r.get("flags")))
    # 27. an unresolved safety axis with no properties[] tag passes the gate but is reported
    #     as gate-silent (red-team 2026-10-19: it passed silently).
    r = pat(dict(base_pat, id="S27", drug="silent",
                 properties=["approved_or_credible_pediatric_path"],
                 safety_assessment={"oncology": "contradictory", "renal": "not_observed",
                                    "growth": "not_assessed"}))
    checks.append(("gate_silent_axes_reported",
                   r["verdict"] != "REJECT" and r.get("gate_silent_safety") == ["growth", "oncology"],
                   r.get("gate_silent_safety")))

    # 28. a recognised risk tag the gate has no rule for at this level is reported, not hidden
    r = pat(dict(base_pat, id="S28", drug="immuno",
                 properties=["approved_or_credible_pediatric_path", "immunosuppressive"],
                 safety_assessment={"oncology": "confirmed_risk", "renal": "not_observed",
                                    "growth": "not_observed"}))
    checks.append(("unactioned_risk_tag_reported",
                   r["verdict"] != "REJECT" and any("immunosuppressive" in x
                                                    for x in r.get("unactioned_risk_tags", [])),
                   r.get("unactioned_risk_tags")))

    ok = all(c[1] for c in checks)
    for name, passed, obs in checks:
        print(f"[{'PASS' if passed else 'FAIL'}] {name}: {obs}")
    print("ALL PASS" if ok else "SOME FAILED")
    return 0 if ok else 1


