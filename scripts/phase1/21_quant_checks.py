DOCS = HERE / "docs"
UA = {"User-Agent": "mva-track2-quant-checks/1.0 (hackathon submission; contact via repo)"}

# ----------------------------------------------------------------------------- power

Z = {0.80: 0.8416212335729143, 0.90: 1.2815515655446004,
     0.95: 1.6448536269514722, 0.975: 1.959963984540054}


def n_per_arm(p1: float, p2: float, alpha: float = 0.05, power: float = 0.80) -> int:
    """兩比例、雙尾、常態近似的每組樣本數（計數單位＝一次分裂或一個細胞）。"""
    za = Z[1 - alpha / 2]
    zb = Z[power]
    pbar = (p1 + p2) / 2
    num = (za * math.sqrt(2 * pbar * (1 - pbar))
           + zb * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2
    return math.ceil(num / (p1 - p2) ** 2)


def design_effect(m: int, icc: float) -> float:
    return 1.0 + (m - 1) * icc


def power_table() -> str:
    m = 100              # 每個培養皿計分的分裂數／細胞數
    iccs = (0.0, 0.01, 0.05)
    rows = []
    for label, baselines in (("Stage C — missegregation events per division", (0.10, 0.20, 0.30)),
                             ("Stage D — aneuploid fraction of the surviving population", (0.20, 0.30, 0.40))):
        for p1 in baselines:
            for rel in (1/3, 1/2):   # exact fractions: '33%' is not one third, and the
                                     # release gate recomputes these cells from 0.30 -> 0.20
                p2 = round(p1 * (1 - rel), 4)
                n = n_per_arm(p1, p2)
                cult = {icc: math.ceil(n * design_effect(m, icc) / m) for icc in iccs}
                rows.append((label, p1, rel, p2, n, cult))
    out = []
    out.append("# Detectability of the staged experiment (report §6)\n")
    out.append("*Generated by `scripts/phase1/21_quant_checks.py power`. Pure arithmetic, no network, "
               "re-run by `run.sh`. Every input is an **assumption**, not a measurement from this child's "
               "cells — see the assumption list below.*\n")
    out.append(f"Two-proportion two-sided test, alpha = 0.05, power = 0.80. "
               f"Counting unit is one scored division (Stage C) or one scored cell (Stage D). "
               f"`cultures/arm` assumes **{m}** units scored per culture and inflates by the design effect "
               f"`1 + (m-1)·ICC` for clustering of units within a culture.\n")
    out.append("| Endpoint | baseline | relative reduction | treated | units/arm | cultures/arm ICC=0 | ICC=0.01 | ICC=0.05 |")
    out.append("|---|---|---|---|---|---|---|---|")
    for label, p1, rel, p2, n, cult in rows:
        out.append(f"| {label} | {p1:.2f} | {'one third' if rel < 0.4 else 'one half'} | {p2:.2f} | {n:,} | "
                   f"{cult[0.0]} | {cult[0.01]} | {cult[0.05]} |")
    ref = next(r for r in rows if r[0].startswith("Stage D") and r[1] == 0.30 and abs(r[2] - 1/3) < 1e-9)
    out.append("")
    out.append(f"**The reference design.** Stage D at a baseline aneuploid fraction of 0.30 and a one-third "
               f"relative reduction (0.30 -> 0.20) needs **{ref[4]:,} scored cells per arm**. At {m} cells per "
               f"culture that is **{ref[5][0.0]} cultures per arm** if units within a culture are independent, "
               f"and **{ref[5][0.05]} cultures per arm** at ICC = 0.05. The design rule stated in §6 "
               f"(≥ 3 independent biological replicates) therefore covers the replicate *structure* and not "
               f"the *power*: three cultures per arm suffice only for a large effect with near-zero "
               f"between-culture variance.")
    out.append("")
    out.append("**What each number assumes, and what would replace it.**\n")
    out.append("- *Baseline rate.* Unmeasured in this child's cells. Stage C's first run is what replaces it; "
               "until then the row to read is a range, not a point.\n"
               "- *Effect size.* No NAD+-raising agent has been tested in this disease or this allele class, so "
               "the one-third / one-half columns are scenario values chosen to bracket a plausible rescue, not predictions. "
               "If the true effect is smaller than a third, every number here is an underestimate.\n"
               "- *ICC.* Between-culture clustering has not been measured for these endpoints. ICC = 0.05 with "
               f"{m} units per culture already multiplies the requirement by {design_effect(m, 0.05):.2f}, which is "
               "why the column exists rather than a single headline n.\n"
               "- *One-sided vs two-sided.* Two-sided throughout, because a rise in the aneuploid fraction is a "
               "result this experiment must be able to detect (§6 Stage D).\n"
               "- *What this is not.* A power calculation is not evidence that the effect exists. It states what "
               "the proposed experiment could see if it did.")
    return "\n".join(out) + "\n"


