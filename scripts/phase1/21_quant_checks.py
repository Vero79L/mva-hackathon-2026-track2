#!/usr/bin/env python3
"""第 21 步：三個可複驗的量化檢查（不含任何病人資料）。

子命令：
  power          分階實驗的可偵測性：兩比例檢定所需樣本數 + 群聚設計效應。純算術，離線，
                 進 run.sh。寫出 docs/power_table.md。
  tractability   Open Targets 的 tractability 掃描（checkpoint/分離模組 + NAD+ 軸共 15 個蛋白），
                 回答「這個模組裡有幾個有核准藥、有藥的往哪個方向走」。需要網路；
                 結果存成有日期的快照 docs/target_tractability.md。
  clinvar-baserate  ClinVar 中 BUB1B 的「後果類別 × 致病性分級」交叉表，用來說明
                 missense 等位基因沒有策展分級是這個基因的常態而非異常。需要網路；
                 快照 docs/clinvar_baserate.md。

查詢只送出基因名稱／Ensembl ID。沒有座標、沒有 genotype、沒有樣本識別碼離開這台機器。
"""
