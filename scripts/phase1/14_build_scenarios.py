#!/usr/bin/env python3
"""第 14 步：base case + 情境表 → 三個（或更多）情境 case 檔（Spec 1 v1.1 第 5 節）。

讀：config/cases/<CASE_ID>.yaml（base）、config/scenarios/<CASE_ID>.scenarios.yaml、$REGISTERS/fact_register.csv
寫：config/cases/<CASE_ID>_S1.yaml、_S2、_S3…（檔頭標 AUTO-GENERATED，不要手改）
檢查：
  - 情境表的 drives = 登錄表裡「會改變方向、而且不是 CONFIRMED」的事實（多一個少一個都 FAIL）
  - 每個情境對每個 drive 都給了值；assumptions 只能用 drives 裡的事實
  - prior_weights 加總 = 1；objective_validity 的類別與值合法
  - base case 有 therapeutic_objectives 時：每個目標的 valid_in_scenarios 和情境表一致
  - 產生的檔案只在 scenario 區塊與 molecular_target_valid 不同
  - （--run-engine）每個情境檔用 src/triage.py 跑一次，必須成功
用法：python3 scripts/phase1/14_build_scenarios.py [--run-engine] [--init]
"""
# Make stdout/stderr UTF-8 regardless of the machine's locale: this repo is read and run by
# reviewers on systems where the preferred encoding may be ASCII, and a crash while *printing*
# a result is still a failed reproduction.
import sys as _sys
for _s in (_sys.stdout, _sys.stderr):
    try: _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception: pass

import argparse
import copy
import csv
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import t2common as C  # noqa: E402

CLASSES = ("restore", "mitigate", "deselect", "protect")
VALIDITY = ("valid", "invalid", "conditional")
HEADER = "# AUTO-GENERATED by scripts/phase1/14_build_scenarios.py — 改 base case 或情境表，不要改這個檔"


def direction_facts(register):
    if not register.exists():
        return None
    with open(register, newline="", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if (r.get("fact_id") or "").strip()]
    return {r["fact_id"].strip(): r for r in rows}


def validate(base, sc, reg_rows):
    fails, warns = [], []
    if base.get("case_id") != sc.get("case_id"):
        fails.append(f"case_id 不一致：base={base.get('case_id')}，情境表={sc.get('case_id')}")
    scen = sc.get("scenarios") or []
    ids = [s.get("id") for s in scen]
    if len(scen) < 2:
        fails.append("至少要兩個情境")
    if len(set(ids)) != len(ids):
        fails.append("情境 id 重複")
    drives = list(sc.get("drives") or [])
    pw = sc.get("prior_weights") or {}
    if set(pw) != set(ids):
        fails.append(f"prior_weights 的鍵 {sorted(pw)} 要和情境 {ids} 一樣")
    elif abs(sum(float(v) for v in pw.values()) - 1.0) > 1e-3:
        fails.append(f"prior_weights 加總是 {sum(float(v) for v in pw.values()):.3f}，要是 1")
    if reg_rows is None:
        warns.append("找不到 fact_register.csv：跳過 drives 與登錄表的比對（第 13 步要先做）")
    else:
        should = {k for k, r in reg_rows.items()
                  if (r.get("would_change_direction") or "").strip() == "yes" and (r.get("status") or "").strip() != "CONFIRMED"}
        missing = should - set(drives)
        extra = set(drives) - set(reg_rows)
        if missing:
            fails.append("登錄表裡會改變方向的未確認事實沒有進 drives：" + "、".join(sorted(missing)))
        if extra:
            fails.append("drives 裡有登錄表沒有的事實：" + "、".join(sorted(extra)))
    for s in scen:
        sid = s.get("id")
        a = s.get("assumptions") or {}
        bad = set(a) - set(drives)
        if bad:
            fails.append(f"{sid}：assumptions 用了不在 drives 裡的事實 {sorted(bad)}")
        lack = [d for d in drives if d not in a or a[d] in (None, "")]
        if lack:
            fails.append(f"{sid}：這些 drive 沒有給值 {lack}")
        imp = s.get("implications") or {}
        ov = imp.get("objective_validity") or {}
        for k, v in ov.items():
            if k not in CLASSES:
                fails.append(f"{sid}：objective_validity 的類別 {k} 不在 {CLASSES}")
            if v not in VALIDITY:
                fails.append(f"{sid}：objective_validity.{k} = {v}，要是 {VALIDITY}")
        if not isinstance(imp.get("molecular_target_valid"), bool):
            fails.append(f"{sid}：implications.molecular_target_valid 要是 true / false")
        if not (s.get("what_would_confirm") or "").strip():
            fails.append(f"{sid}：what_would_confirm 要寫（哪個量測、什麼結果會確認這個情境）")
    # 治療目標和情境表一致
    for obj in base.get("therapeutic_objectives") or []:
        cls = obj.get("class")
        if cls not in CLASSES:
            fails.append(f"therapeutic_objectives：{obj.get('id')} 的 class {cls} 不合法")
            continue
        declared = set(obj.get("valid_in_scenarios") or [])
        derived = {s["id"] for s in scen if ((s.get("implications") or {}).get("objective_validity") or {}).get(cls) == "valid"}
        if declared != derived:
            fails.append(f"therapeutic_objectives：{obj.get('id')}（{cls}）的 valid_in_scenarios={sorted(declared)}，"
                         f"但情境表說 valid 的是 {sorted(derived)}")
    return fails, warns


def build(base, sc, src_name):
    out = {}
    for s in sc["scenarios"]:
        c = copy.deepcopy(base)
        c["case_id"] = f"{base['case_id']}_{s['id']}"
        c["scenario"] = {"id": s["id"], "label": s.get("label"), "assumptions": s.get("assumptions"),
                         "implications": s.get("implications"), "what_would_confirm": s.get("what_would_confirm"),
                         "prior_weight": sc["prior_weights"][s["id"]], "source": src_name}
        c["molecular_target_valid"] = bool(s["implications"]["molecular_target_valid"])
        out[s["id"]] = c
    return out


def drift_ok(docs, base_id):
    norm = []
    for d in docs:
        d = copy.deepcopy(d)
        d.pop("scenario", None)
        d.pop("molecular_target_valid", None)
        d["case_id"] = base_id
        norm.append(d)
    return all(d == norm[0] for d in norm)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-engine", action="store_true", help="每個情境檔用 src/triage.py 跑一次")
    ap.add_argument("--candidates", default="evidence/candidates_from_canonical.yaml")
    ap.add_argument("--init", action="store_true", help="情境表不存在時從範本建立")
    a = ap.parse_args()
    env = C.load_env()
    eng = C.ENGINE
    cid = env.get("CASE_ID", "bub1b_mva")
    base_p = eng / "config" / "cases" / f"{cid}.yaml"
    sc_p = eng / "config" / "scenarios" / f"{cid}.scenarios.yaml"
    if not sc_p.exists():
        if not a.init:
            C.die(f"找不到 {sc_p}。第一次用 --init 從範本建立，再照 Spec 1 第 5.1 節填")
        sc_p.parent.mkdir(parents=True, exist_ok=True)
        text = (eng / "templates" / "phase1" / "scenarios.TEMPLATE.yaml").read_text(encoding="utf-8")
        sc_p.write_text(text.replace("<CASE_ID>", cid), encoding="utf-8")
        C.ok(f"已從範本建立 {sc_p}")
        return
    base = C.read_yaml(base_p)
    sc = C.read_yaml(sc_p)
    reg = direction_facts(C.path("REGISTERS", env) / "fact_register.csv")
    fails, warns = validate(base, sc, reg)
    for w in warns:
        C.warn(w)
    if fails:
        for f in fails:
            print(f"  ✗ {f}")
        C.die(f"{len(fails)} 個問題要修（Spec 1 第 5 節）")
    docs = build(base, sc, sc_p.name)
    written = []
    for sid, d in docs.items():
        p = base_p.with_name(f"{cid}_{sid}.yaml")
        C.write_yaml(p, d, header=HEADER)
        written.append(p)
    if not drift_ok([C.read_yaml(p) for p in written], cid):
        C.die("產生的情境檔在 scenario 以外的欄位不一致（不應該發生：回報這個錯誤）")
    C.ok(f"寫出 {', '.join(p.name for p in written)}；三檔只差在 scenario 區塊")
    if a.run_engine:
        py = sys.executable
        for p in [base_p] + written:
            r = subprocess.run([py, "src/triage.py", "--case", str(p.relative_to(eng)), "--candidates", a.candidates],
                               cwd=eng, capture_output=True, text=True)
            if r.returncode != 0:
                print(r.stdout[-2000:], r.stderr[-2000:])
                C.die(f"引擎跑 {p.name} 失敗")
            C.ok(f"引擎接受 {p.name}")


if __name__ == "__main__":
    main()
