#!/bin/sh
# One clean run: selftest -> generate views -> real case -> synthetic case.
# Any step failure exits non-zero (no pipeline masking).
cd "$(dirname "$0")" || exit 1
PY="${PYTHON:-python3}"
export PYTHONIOENCODING=utf-8 PYTHONUTF8=1
# Preflight: every step needs PyYAML. Fail here with an actionable message rather than three
# steps in with a bare ModuleNotFoundError (a reviewer running this on a stock python3 hit
# exactly that on 2026-10-19).
if ! "$PY" -c "import yaml" >/dev/null 2>&1; then
  echo "This needs PyYAML, and '$PY' does not have it." >&2
  echo "  install it :  $PY -m pip install -r requirements.txt" >&2
  echo "  or point at an interpreter that has it:  PYTHON=\$(which python) ./run.sh" >&2
  exit 1
fi
mkdir -p outputs
OUT=outputs/run.txt
: > "$OUT"
step() {
  name="$1"; shift
  echo "== $name ==" >> "$OUT"
  "$@" >> "$OUT" 2>&1
  rc=$?
  if [ "$rc" -ne 0 ]; then echo "STEP FAILED ($name) rc=$rc" >> "$OUT"; echo "STEP FAILED ($name) rc=$rc"; exit "$rc"; fi
}
step selftest "$PY" src/triage.py --selftest
step "generate views" "$PY" build_views.py
step "real case" "$PY" src/triage.py --case config/cases/bub1b_mva.yaml --candidates evidence/candidates_from_canonical.yaml
step "synthetic case" "$PY" src/triage.py --case config/cases/synthetic_gof_demo.yaml --candidates evidence/candidates_synthetic.yaml
# Scenario sensitivity (S1/S2/S3 case files are generated by scripts/phase1/14_build_scenarios.py)
for sc in S1 S2 S3; do
  if [ -f "config/cases/bub1b_mva_$sc.yaml" ]; then
    step "scenario $sc" "$PY" src/triage.py --case "config/cases/bub1b_mva_$sc.yaml" --candidates evidence/candidates_from_canonical.yaml
  else
    echo "== scenario $sc == (skipped: config/cases/bub1b_mva_$sc.yaml not present yet)" >> "$OUT"
  fi
done
# Detectability of the proposed experiment: pure arithmetic, no network, so the table in the
# report cannot drift from the numbers it claims. The two network-dependent quantitative
# checks (tractability, clinvar-baserate) are dated snapshots and are NOT re-run here:
# run.sh must stay runnable offline.
step power "$PY" scripts/phase1/21_quant_checks.py power
# Robustness harness: ablation, constraint perturbation, name blinding, synthetic
# probes, leave-one-source-out. R3/R4 are assertions and exit non-zero on failure,
# so a regression that makes the engine name-dependent fails the build here.
step robustness "$PY" scripts/phase1/20_robustness.py
step "claim ledger" "$PY" make_claim_ledger.py
# Release manifest: the four deliverables must agree with the canonical sources (Spec 0 §1.2)
step "manifest" "$PY" make_manifest.py
echo "DONE" >> "$OUT"; echo "DONE (see $OUT)"
